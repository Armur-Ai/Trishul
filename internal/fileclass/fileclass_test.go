func TestClassifyWindowsPaths(t *testing.T) {
	if got := Classify(`vendor\github.com\foo\bar.go`, nil); got != KindVendored {
		t.Errorf("windows vendor path = %q, want %q", got, KindVendored)
	}
	if got := Classify(`.\README.md`, nil); got != KindDocs {
		t.Errorf("dot-slash readme = %q, want %q", got, KindDocs)
	}
}

func TestReadmePlainIsNotLocale(t *testing.T) {
	// README.md at root is docs, README.<lang>.md is locale.
	if got := Classify("README.md", nil); got != KindDocs {
		t.Errorf("README.md = %q, want %q", got, KindDocs)
	}
	if got := Classify("README.zh.md", nil); got != KindLocale {
		t.Errorf("README.zh.md = %q, want %q", got, KindLocale)
	}
}

func TestAgentSurfaceBeatsDocs(t *testing.T) {
	// CLAUDE.md in a docs tree must still be agent-surface, not docs.
	if got := Classify("docs/guides/CLAUDE.md", nil); got != KindAgentSurface {
		t.Errorf("docs CLAUDE.md = %q, want %q", got, KindAgentSurface)
	}
}

func TestGeneratedHeaderOnlyScansTop(t *testing.T) {
	// A marker below the first few lines must not trigger generated.
	content := []byte(strings.Repeat("package foo\n", 10) + "// @generated\n")
	if got := Classify("foo.go", content); got != KindSource {
		t.Errorf("late marker = %q, want %q", got, KindSource)
	}
}

func TestMinifiedRequiresContent(t *testing.T) {
	// An ordinary .js with normal content is source, not minified.
	if got := Classify("src/app.js", []byte("const x = 1;\nconsole.log(x);\n")); got != KindSource {
		t.Errorf("normal js = %q, want %q", got, KindSource)
	}
	// Empty content never trips the line-length heuristic.
	if got := Classify("src/app.js", []byte{}); got != KindSource {
		t.Errorf("empty js = %q, want %q", got, KindSource)
	}
}

func TestIsCodeLike(t *testing.T) {
	codeLike := []Kind{
		KindSource, KindTest, KindExample, KindConfig, KindCI,
		KindMigration, KindAgentSurface,
	}
	notCodeLike := []Kind{
		KindDocs, KindLocale, KindGenerated, KindVendored,
		KindMinified, KindFixture,
	}
	for _, k := range codeLike {
		if !k.IsCodeLike() {
			t.Errorf("%q.IsCodeLike() = false, want true", k)
		}
	}
	for _, k := range notCodeLike {
		if k.IsCodeLike() {
			t.Errorf("%q.IsCodeLike() = true, want false", k)
		}
	}
}

func TestHasSegment(t *testing.T) {
	cases := []struct {
		path, seg string
		want      bool
	}{
		{"a/vendor/b", "vendor", true},
		{"avendored/b", "vendor", false},
		{"vendor/b", "vendor", true},
		{"a/vendor", "vendor", true},
		{"a/b/c", "vendor", false},
		{"vendor", "vendor", true},
		{"a/vendor/b", "vendor/", true},
		{"", "vendor", false},
	}
	for _, tc := range cases {
		if got := hasSegment(tc.path, tc.seg); got != tc.want {
			t.Errorf("hasSegment(%q, %q) = %v, want %v", tc.path, tc.seg, got, tc.want)
		}
	}
}
